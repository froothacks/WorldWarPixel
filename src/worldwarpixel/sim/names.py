def random_name(country: str, rng: random.Random, used: set[str]) -> str:
    firsts, lasts = NAME_POOLS.get(country, NAME_POOLS["Rest of world"])
    for _ in range(50):
        name = f"{rng.choice(firsts)} {rng.choice(lasts)}"
        if name not in used:
            used.add(name)
            return name
    name = f"{rng.choice(firsts)} {rng.choice(lasts)} {len(used) + 1}"
    used.add(name)
    return name
